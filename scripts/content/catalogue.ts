import type { TrackSummary } from "../../src/shared/domain.ts";
import type { TrackManifest } from "./model.ts";

export function buildCatalogueEntry(
  manifest: TrackManifest,
  durationSec: number,
  hasGuide: boolean,
): TrackSummary {
  const variants = (manifest.transpositions ?? [0]).map((transposeSemitones) => ({
    transposeSemitones,
    audioUrl:
      transposeSemitones === 0
        ? `/audio/${manifest.id}.backing.mp3`
        : `/audio/${manifest.id}.backing.t${transposeSemitones}.mp3`,
    ...(hasGuide
      ? {
          guideUrl:
            transposeSemitones === 0
              ? `/audio/${manifest.id}.guide.mp3`
              : `/audio/${manifest.id}.guide.t${transposeSemitones}.mp3`,
        }
      : {}),
  }));

  return {
    id: manifest.id,
    title: manifest.title,
    artist: manifest.artist,
    durationSec,
    difficulty: manifest.difficulty,
    licence: manifest.licence,
    audioLicence: manifest.audioLicence,
    attribution: manifest.attribution,
    sourceUrl: manifest.sourceUrl,
    audioUrl: `/audio/${manifest.id}.backing.mp3`,
    ...(hasGuide ? { guideUrl: `/audio/${manifest.id}.guide.mp3` } : {}),
    audioVariants: variants,
    chartUrl: `/charts/${manifest.id}.json`,
    ...(manifest.keySignature ? { keySignature: manifest.keySignature } : {}),
    tempoBpm: manifest.tempoBpm,
    ...(manifest.soundfont ? { soundfont: manifest.soundfont } : {}),
  };
}

const DIFFICULTY_ORDER = { easy: 0, medium: 1, hard: 2 } as const;

export function compareCatalogue(a: TrackSummary, b: TrackSummary): number {
  return (
    DIFFICULTY_ORDER[a.difficulty] - DIFFICULTY_ORDER[b.difficulty] ||
    a.title.localeCompare(b.title)
  );
}

export function renderCatalogue(entries: TrackSummary[]): string {
  return [
    "// Generated by `npm run content:build`. Do not edit by hand.",
    'import type { TrackSummary } from "../shared/domain";',
    "",
    `export const TRACKS: TrackSummary[] = ${JSON.stringify(entries, null, 2)};`,
    "",
  ].join("\n");
}
